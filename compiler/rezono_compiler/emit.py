HEADER = "-- Generated by the Rezono compiler from the pack schemas. Do not edit.\n"
RULES_HEADER = "-- Generated by the Rezono compiler from the pack rules (rules/*.dl). Do not edit.\n"
# The budget per Feldera pipeline comes from the deploy profile (deploy/profiles/<profile>.yaml):
# engine.build_memory_mb with engine.view_cost_mb, the build memory of each kind of view as probes/budget
# measured it; or engine.view_budget, a number of rule views. Without a profile: the 64 of the M2 probe.
MAX_VIEWS = 64
# The stable code of the warning that the batch backend refuses the rule program (E10): the compile succeeds,
# and batch/rules.sql fails with the reason when it runs.
BATCH_REFUSES = "batch_refuses_rules"
# The kinds of view a pipeline holds; `base` is the build of a pipeline without views.
VIEW_KINDS = ("base", "check", "seal", "relation", "witness", "outcome", "calc", "export")
# Patterns are matched with RLIKE(text, pattern), as in Feldera (Rust regex, search). DuckDB runs the same
# SQL after this macro (RE2, search); regex.portable keeps patterns to the subset on which both agree.
DUCKDB_FUNCTIONS = "CREATE OR REPLACE MACRO rlike(s, p) AS regexp_matches(s, p);\n"


def duckdb(sql: str) -> str:
    """Evaluate shared engine SQL on DuckDB with logical relation names and plain views."""
    logical = feldera_names.render(sql, feldera_names.LOGICAL)
    return logical.replace("CREATE MATERIALIZED VIEW", "CREATE VIEW").replace("CREATE LOCAL VIEW", "CREATE VIEW")
# Parameter tables per slot (docs/compiler.md): the facet that gives the row, and the column type.
SLOT_PARAMETERS = (("minimum", "minimum"), ("maximum", "maximum"), ("constant", "constant"),
                   ("minimum_cardinality", "minimum_cardinality"), ("maximum_cardinality", "maximum_cardinality"))


@dataclass(frozen=True)
class Memory:
    """A build-memory budget: what one Feldera build may take, and what each kind of view
    costs (VIEW_KINDS), in whole MB."""
    build_mb: int
    cost_mb: tuple[tuple[str, int], ...]

    def cost(self, kind: str) -> int:
        return dict(self.cost_mb)[kind]


def whole(v) -> bool:
    return isinstance(v, int) and not isinstance(v, bool)


def view_budget(profile: dict) -> int | Memory:
    """The budget of a deploy profile (deploy/profiles/<profile>.yaml): a build memory with a cost per kind
    of view, or a number of views."""
    engine, name = profile.get("engine") or {}, profile.get("profile")
    if "build_memory_mb" in engine:
        memory, costs = engine["build_memory_mb"], engine.get("view_cost_mb") or {}
        if not whole(memory) or memory < 1:
            raise CompileError(f"profile {name}: engine.build_memory_mb must be a positive whole number")
        if sorted(costs) != sorted(VIEW_KINDS) or not all(whole(v) and v >= 0 for v in costs.values()):
            raise CompileError(f"profile {name}: engine.view_cost_mb must give a whole number of MB for each of "
                               + ", ".join(VIEW_KINDS))
        return Memory(memory, tuple((k, costs[k]) for k in VIEW_KINDS))
    budget = engine.get("view_budget")
    if not whole(budget) or budget < 1:
        raise CompileError(f"profile {name}: engine.view_budget must be a positive whole number")
    return budget


def previous_parts(plan: dict) -> list[list[str]]:
    """The partition of an earlier engine/pipelines.json: the rule views per part place. `rules-<n>` is
    place n; `main` (one pipeline) is place 1; a place without a pipeline is an empty list."""
    places = {}
    for p in plan.get("pipelines", []):
        if p.get("views"):
            places[1 if p["name"] == "main" else int(p["name"].split("-")[1])] = p["views"]
    return [places.get(n, []) for n in range(1, max(places, default=0) + 1)]


def compile_pack(pack: Pack, max_views: int | Memory = MAX_VIEWS, previous: list[list[str]] | None = None,
                 profile: str | None = None) -> dict[str, str]:
    """All output files, keyed by relative path. `max_views` is the budget per pipeline: a number of rule
    views, or a build memory (Memory)."""
    checks = integrity(pack)
    prog = ir.load(pack.rules) if pack.rules else None
    calc_prog = calc.build(pack, pack.calc) if pack.calc is not None else None
    namespace(pack, checks, prog, calc_prog)
    check_sql, check_views = bundled.views(pack, checks)  # one view per check kind
    out = {
        "engine/tables.sql": tables(pack, relation=feldera_names.quoted),
        "engine/integrity.sql": HEADER + feldera_names.render(check_sql + seal.sql(pack)),
        "engine/parameters.json": rows_json(parameters(pack)),
        "bundle/schema-bundle.json": json.dumps(bundle(pack, checks, prog, calc_prog), ensure_ascii=False, indent=2) + "\n",
    }
    if prog:
        out.update(rule_files(pack, prog, max_views, previous, profile, calc_prog, check_views))
    elif pack.seals:  # the checker recomputes the seal from the rule IR, also when there are no rules
        from .rules_dl import seal_docs
        out["ir/rules.json"] = json.dumps({"format": ir.FORMAT, "pack": pack.meta["name"], "relations": [], "rules": [],
                                           "seals": seal_docs(pack)}, ensure_ascii=False, indent=2) + "\n"
    if calc_prog:
        out.update(calc_files(calc_prog, out))
    if pack.sweeps:  # read by the publisher, which computes one epoch per grid value
        out["ir/sweeps.json"] = json.dumps({"format": "rezono.sweeps/1", "sweeps": pack.sweeps}, ensure_ascii=False,
                                           indent=2) + "\n"
    return dict(sorted(out.items()))


def calc_files(prog, out: dict[str, str]) -> dict[str, str]:
    """The calculation rules: Feldera views (with the UDF in udf/), the DuckDB script, and the
    evaluation date as a fact row. They read the tables and the derived relations, so with rules they
    join the rule pipeline."""
    files = {
        "engine/calc.sql": calc_sql.feldera(prog),
        "batch/calc.sql": calc_sql.duckdb(prog),
        "engine/calc.json": rows_json(calc_sql.rows(prog)),
        "ir/calc.json": json.dumps(calc.to_doc(prog), ensure_ascii=False, indent=2) + "\n",
    }
    if "engine/pipelines.json" in out:
        plan = json.loads(out["engine/pipelines.json"])
        if plan["pipelines"][0]["name"] != "main":
            return files  # split: rule_files gave the calculation a pipeline of its own
        main = plan["pipelines"][0]
        main["sql"].append("engine/calc.sql")  # its views stay out of "views": that lists the rule views per part
        main["tables"] = sorted(main["tables"] + [calc_sql.AS_OF])
        files["engine/pipelines.json"] = json.dumps(plan, ensure_ascii=False, indent=2) + "\n"
    return files



def rule_files(pack: Pack, prog, max_views, previous=None, profile=None, calc_prog=None, n_checks=0) -> dict[str, str]:
    """The rule IR, the Feldera views, the batch script and the partition.
    Split (docs/compiler.md#pipeline-partition): `integrity` computes the seal's relations once and forwards
    them to the parts that read them. The calculation pipeline follows its rule dependencies and
    precedes rules that read its output."""
    every_table = sorted([k for k in pack.kinds] + [s.table for kind in pack.kinds.values() for s in kind.slots.values()]
                         + list(parameters(pack)) + [s.row_sha256 for s in pack.seals])
    calc_inputs = prog.calc_inputs()
    before, after = (None, None)
    if calc_inputs:
        if calc_prog is None:
            raise CompileError("rules: calculation inputs require a calculation program")
        before, after = prog.partition_at_calc(calc_inputs, calc_sql.derived_reads(calc_prog))
    late_batch = None
    try:
        batch = "\n\n".join(rules_sql.duckdb_program(prog, "materialize", relations=before)) + "\n"
        if calc_inputs:
            late_batch = "\n\n".join(calc_sql.duckdb_rule_inputs(calc_inputs)
                                      + rules_sql.duckdb_program(prog, "materialize", relations=after)) + "\n"
    except NotImplementedError as e:
        # E10: a refusal of the batch backend is its own. Feldera keeps its output; the batch script
        # fails with the reason, so the two engines never silently disagree.
        batch = "SELECT error(" + literal(f"rules: {e}") + ");\n"
        print(f"warning: rules: {BATCH_REFUSES}: {e}; batch/rules.sql fails with this reason when it runs",
              file=sys.stderr)
    out = {
        "ir/rules.json": json.dumps(ir.to_doc(prog), ensure_ascii=False, indent=2) + "\n",
        "engine/rules.sql": RULES_HEADER + rules_sql.feldera(prog, witnesses="materialize", tables=False),
        "batch/rules.sql": RULES_HEADER + batch,
    }
    if late_batch is not None:
        out["batch/rules-late.sql"] = RULES_HEADER + late_batch
    budget = Cost(pack, prog, calc_prog, n_checks, max_views)
    calc_position = None
    try:
        if calc_inputs:
            old = previous or []
            late_names = set(after)
            boundary = next((i for i, part in enumerate(old) if late_names.intersection(part)), len(old))
            early = rules_split.partition(prog, budget.part, old[:boundary],
                                          cost=budget.relation, unit=budget.unit, relations=before)
            late = rules_split.partition(prog, budget.part, old[boundary:],
                                         cost=budget.relation, unit=budget.unit, relations=after)
            parts = early + late
            calc_position = 1 + sum(bool(part) for part in early)  # integrity, then the nonempty early parts
        else:
            parts = rules_split.partition(prog, budget.part, previous, budget.relation, budget.whole, budget.unit)
    except rules_split.TooBig as e:
        raise CompileError(f"rules: {e}") from None
    # Exceeding the budget warns. Only a recursive core above it blocks (in the partition).
    for name, costs in rules_split.over_budget(prog, parts, budget.part, budget.relation):
        print(f"warning: rules: {name} costs {costs} {budget.unit}, more than the budget of {budget.part} per "
              "pipeline; it is not recursive, so it gets a pipeline of its own", file=sys.stderr)
    upstream = {n for s in pack.seals for n in (s.refused, s.accepted, *(p.accepted for p in s.parts))}
    plan = rules_split.plan(prog, parts, upstream.union(calc_inputs))
    pipelines = []
    if len(parts) == 1 and calc_position is None:
        pipelines.append({"name": "main", "sql": ["engine/tables.sql", "engine/integrity.sql", "engine/rules.sql"],
                          "modules": prog.modules(), "views": plan[0]["views"], "tables": every_table,
                          "imports": [], "exports": []})
    else:
        sealed = sorted({r for part in plan for r in part["imports"] if r in upstream})
        integrity_sql = ["engine/tables.sql", "engine/integrity.sql"]
        if sealed:
            out["engine/integrity-export.sql"] = HEADER + rules_split.export_sql(prog, sealed)
            integrity_sql.append("engine/integrity-export.sql")
        pipelines.append({"name": "integrity", "sql": integrity_sql,
                          "modules": [], "views": [], "tables": every_table, "imports": [], "exports": sealed})
        for i, part in enumerate(plan, 1):
            if not part["views"]:
                continue        # a place emptied since the previous compile keeps its number
            out[f"engine/rules-{i}.sql"] = RULES_HEADER + rules_split.part_sql(prog, part)
            mods = [m for m in prog.modules() if any(prog.relations[n].module == m for n in part["views"])]
            pipelines.append({"name": f"rules-{i}", "sql": [f"engine/rules-{i}.sql"], "modules": mods,
                              "views": part["views"], "tables": part["bases"],
                              "imports": part["imports"], "exports": part["exports"]})
        if calc_prog:
            calculation = calc_pipeline(prog, calc_prog, plan, pipelines, out, calc_inputs)
            if calc_position is None:
                pipelines.append(calculation)
            else:
                if budget.memory and budget.estimate(calculation) > budget.memory.build_mb:
                    raise CompileError("rules: calculation and its exports exceed the build memory budget")
                pipelines.insert(calc_position, calculation)
    names = {n: p["name"] for p in pipelines for n in p["exports"]}
    forward = [{"relation": r, "producer": names[r], "consumers": sorted(p["name"] for p in pipelines if r in p["imports"])}
               for r in sorted({r for p in pipelines for r in p["imports"]})]
    plan_doc = budget.annotate(pipelines)
    if profile:
        plan_doc["profile"] = profile
    out["engine/pipelines.json"] = json.dumps(plan_doc | {
        "pipelines": pipelines, "forward": forward, "epoch_table": rules_split.EPOCH, "export_view": rules_split.EXPORT,
    }, ensure_ascii=False, indent=2) + "\n"
    return out


class Cost:
    """The budget of a pipeline in the partition's terms. Counted in views, a part holds
    `views` rule views and so does `main`. Weighed in build memory, a relation costs its views by kind;
    a part holds the build memory less a pipeline's base and its export, and `main` also holds the
    integrity checks, the seal and the calculation rules. The plan records the estimate per pipeline."""

    def __init__(self, pack, prog, calc_prog, n_checks: int, budget):
        self.prog, self.memory = prog, budget if isinstance(budget, Memory) else None
        self.views = {"check": n_checks, "seal": sum(2 + len(s.parts) for s in pack.seals),
                      "calc": len(calc_sql.relations(calc_prog)) if calc_prog else 0}
        if self.memory is None:
            self.part = self.whole = budget
            self.relation, self.unit = None, "views"
            return
        c = self.memory.cost
        self.part = self.memory.build_mb - c("base") - c("export")
        self.whole = self.memory.build_mb - c("base") - sum(c(k) * n for k, n in self.views.items())
        self.relation, self.unit = self.weigh, "MB"

    def weigh(self, name: str) -> int:
        return sum(self.memory.cost(k) * n for k, n in rules_split.views_by_kind(self.prog, name).items())

    def estimate(self, p: dict) -> int:
        """The estimated build memory of one pipeline of the plan."""
        c = self.memory.cost
        mb = c("base") + sum(self.weigh(n) for n in p["views"]) + (c("export") if p["exports"] else 0)
        if p["name"] in ("main", "integrity"):
            mb += c("check") * self.views["check"] + c("seal") * self.views["seal"]
        if p["name"] in ("main", "calc"):
            mb += c("calc") * (self.views["calc"] + len(p["exports"]))
        return mb

    def annotate(self, pipelines: list[dict]) -> dict:
        """The head of engine/pipelines.json; with a build memory, the estimate per pipeline too."""
        if self.memory is None:
            return {"format": "rezono.pipelines/1", "max_views": str(self.part)}
        for p in pipelines:
            p["build_mb"] = str(self.estimate(p))
        return {"format": "rezono.pipelines/1", "build_memory_mb": str(self.memory.build_mb)}


def calc_pipeline(prog, calc_prog, plan, pipelines, out: dict[str, str], exports=()) -> dict:
    """The calculation's imports from earlier rule parts and its selection exports to later parts."""
    reads = calc_sql.derived_reads(calc_prog)
    owner = {n: i for i, part in enumerate(plan, 1) for n in part["views"]}
    for i in sorted({owner[r] for r in reads}):
        part, pipe = plan[i - 1], next(p for p in pipelines if p["name"] == f"rules-{i}")
        part["exports"] = pipe["exports"] = sorted(set(part["exports"]) | {r for r in reads if owner[r] == i})
        out[f"engine/rules-{i}.sql"] = RULES_HEADER + rules_split.part_sql(prog, part)
    out["engine/calc-imports.sql"] = RULES_HEADER + rules_sql.input_tables(prog, reads)
    sql = ["engine/tables.sql", "engine/calc-imports.sql", "engine/calc.sql"]
    if exports:
        views = [calc_sql.rule_input_view(selection) for selection in exports]
        out["engine/calc-export.sql"] = HEADER + "\n\n".join(
            f"CREATE VIEW {q(name)} AS\n{body};" for name, body in views
        ) + "\n\n" + rules_split.export_sql(prog, exports)
        sql.append("engine/calc-export.sql")
    return {"name": "calc", "sql": sql, "modules": [], "views": [], "tables": calc_sql.table_reads(calc_prog),
            "imports": reads, "exports": list(exports)}


def namespace(pack: Pack, checks, prog=None, calc_prog=None) -> None:
    """Tables, parameter tables and views share one namespace in the engine; a clash is an error."""
    own = ([k for k in pack.kinds] + [s.table for kind in pack.kinds.values() for s in kind.slots.values()]
           + list(pack.enums))
    reserved = sorted(n for n in own if n == bundled.RESERVED or n.startswith(bundled.P))
    if reserved:  # the engine's own names start with rezono__
        raise CompileError("\n".join(f"engine name '{n}' is reserved for the engine" for n in reserved))
    names = ([k for k in pack.kinds] + [s.table for kind in pack.kinds.values() for s in kind.slots.values()]
             + list(parameters(pack)) + [c[0] for c in checks] + ["validation_result"]
             + [n for n in bundled.names(pack) if n not in bundled.rows(pack)]
             + [n for n, _ in seal.views(pack)] + [s.row_sha256 for s in pack.seals])
    if calc_prog:
        names += [name for name, _, _ in calc_sql.relations(calc_prog)] + [calc_sql.AS_OF]
    if prog:
        names += [n for n, r in prog.relations.items() if r.role == "derived"]
        names += [ir.calc_input_table(n) for n, r in prog.relations.items() if r.role == "calc"]
        names += [r.witness_relation for r in prog.rules.values()] + [rules_split.EPOCH, rules_split.EXPORT]
        names += [v for n in prog.relations for v, _ in rules_sql.checks(prog, n)]
    clashes = sorted({n for n in names if names.count(n) > 1})
    if clashes:
        raise CompileError("\n".join(f"engine name '{n}' is generated twice" for n in clashes))


def rows_json(tables: dict[str, list[dict]]) -> str:
    """One row per line, so that a diff shows which parameter changed."""
    if not tables:
        return "{}\n"
    body = ",\n".join(f"  {json.dumps(t)}: []" if not rows else
                      f"  {json.dumps(t)}: [\n" + ",\n".join(f"    {json.dumps(r, ensure_ascii=False)}" for r in rows)
                      + "\n  ]" for t, rows in tables.items())
    return "{\n" + body + "\n}\n"


def id_type(pack: Pack, kind: str) -> str:
    return pack.kinds[pack.root(kind)].id_type


def tables(pack: Pack, relation=q) -> str:
    out = [HEADER]
    for k, kind in pack.kinds.items():
        out.append(f"\nCREATE TABLE {relation(k)} (id {id_type(pack, k)} NOT NULL);\n")
        for s in kind.slots.values():
            out.append(f"CREATE TABLE {relation(s.table)} (id {id_type(pack, k)} NOT NULL, v {s.type.sql} NOT NULL);\n")
    for s in pack.seals:  # the loader fills it with each element's row hash; the engine never hashes
        out.append(f"\n-- Seal: the canonical hash of each row of {s.kind}, from the loader.\n"
                   f"CREATE TABLE {relation(s.row_sha256)} (id {id_type(pack, s.kind)} NOT NULL, v VARCHAR NOT NULL);\n")
    out.append("\n-- Parameters: enum values, bounds, constants and cardinalities are rows "
               "(engine/parameters.json), not SQL constants.\n")
    for e in pack.enums:
        out.append(f"CREATE TABLE {relation(e)} (id VARCHAR NOT NULL);\n")
    for table, sql_type, _ in slot_parameters(pack):
        out.append(f"CREATE TABLE {relation(table)} (v {sql_type} NOT NULL);\n")
    if pack.kinds:
        out.append(bundled.tables())
    return "".join(out)


def slot_parameters(pack: Pack) -> list[tuple[str, str, object]]:
    """(table, type, value) for every bound, constant and cardinality of a slot that a rule reads, in a fixed
    order. The checks read the rows of rezono__*, so a bound no rule reads is only a row and
    changing it is no build; the rule IR lists the base tables its rules read."""
    read = {r["name"] for r in (pack.rules or {}).get("relations", []) if r["role"] == "base"}
    out = []
    for kind in pack.kinds.values():
        for s in kind.slots.values():
            for facet, suffix in SLOT_PARAMETERS:
                v, table = getattr(s, facet), f"{s.table}__{suffix}"
                if v is not None and table in read:
                    out.append((table, s.type.sql if facet == "constant" else "BIGINT", v))
    return out


def parameters(pack: Pack) -> dict[str, list[dict]]:
    """Parameter rows per table, loaded like facts so that a change is a delta, not a recompile."""
    out = {e: [{"id": v} for v in values] for e, values in pack.enums.items()}
    for table, _, v in slot_parameters(pack):
        out[table] = [{"v": v}]
    if pack.kinds:  # which slot has which check
        out |= bundled.rows(pack)
    return dict(sorted(out.items()))


def view(name: str, body: str) -> str:
    return f"\nCREATE MATERIALIZED VIEW {q(name)} AS\n{body};\n"


def path_sql(pack: Pack, kind: str, path: list[str]) -> str:
    """Rows (id, v): every end reached from an element of `kind` along `path`."""
    joins, prev = [f"FROM {q(kind)} e"], "e.id"
    for i, step in enumerate(path, 1):
        s = pack.slot(kind, step)
        joins.append(f"JOIN {q(s.table)} p{i} ON p{i}.id = {prev}")
        prev, kind = f"p{i}.v", s.range
    return f"SELECT e.id AS id, {prev} AS v " + " ".join(joins)


def integrity(pack: Pack) -> list[tuple]:
    """The logical checks as (name, check, kind, subject, query, path, value), in a fixed order;
    `checks.views` makes one view per check kind of them. A generic check
    (`checks.GENERIC`) is rows of the metadata tables and has no query; the others (`checks.PER_CHECK`)
    carry theirs, with the SQL expression of the value they report.

    The checks follow the translation of linkml-datalog (SHACL-style results), written as Feldera SQL;
    docs/compiler.md maps each check to its SHACL component.
    """
    out = []

    def add(kind, subject, check, body=None, path="", value="''"):
        name = f"{kind}__{subject}__{check}" if subject else f"{kind}__{check}"
        out.append((name, check, kind, subject, body, path, value))

    for k, kind in pack.kinds.items():
        add(k, "", "identification")
        if kind.parent:
            add(k, "is_a", "reference", path="is_a")
        if kind.id_patterns:
            add(k, kind.identifier, "pattern", f"SELECT DISTINCT id, id AS v FROM {q(k)} WHERE {mismatch('id', kind)}",
                path=kind.identifier, value="v")
        for s in kind.slots.values():
            t = q(s.table)
            if s.required:
                add(k, s.name, "totality", path=s.name)
            if not s.multivalued:
                add(k, s.name, "functionality", path=s.name)
            add(k, s.name, "reference", path=s.name)
            if s.enum or any(getattr(s, b) is not None for b in ("minimum", "maximum", "constant")):
                add(k, s.name, "value_range", path=s.name)
            if s.patterns:
                add(k, s.name, "pattern", f"SELECT DISTINCT id, v FROM {t} WHERE {mismatch('v', s)}",
                    path=s.name, value="v")
            if s.minimum_cardinality is not None or s.maximum_cardinality is not None:
                add(k, s.name, "cardinality", path=s.name)
        for name, slots in kind.unique_keys:
            cols = ", ".join(f"c{i}.v AS c{i}" for i in range(len(slots)))
            joins = " ".join(f"JOIN {q(pack.slot(k, sn).table)} c{i} ON c{i}.id = e.id" for i, sn in enumerate(slots))
            same = " AND ".join(f"a.c{i} = b.c{i}" for i in range(len(slots)))
            add(k, name, "unique", f"WITH t AS (SELECT e.id AS id, {cols} FROM {q(k)} e {joins})\n"
                                   f"SELECT DISTINCT a.id AS id FROM t a JOIN t b ON {same} AND a.id <> b.id",
                path=",".join(slots))
        for name, left, right in kind.path_equations:
            add(k, name, "path_equation",
                f"WITH l AS ({path_sql(pack, k, left)}),\n     r AS ({path_sql(pack, k, right)})\n"
                f"SELECT DISTINCT l.id AS id, l.v AS left_end, r.v AS right_end "
                f"FROM l JOIN r ON r.id = l.id WHERE l.v <> r.v",
                path=f"{'.'.join(left)} = {'.'.join(right)}",
                value="CAST(left_end AS VARCHAR) || ' <> ' || CAST(right_end AS VARCHAR)")
        for r in kind.rules:
            pre, post, otherwise = (conjunction(pack, k, cs) for cs in (r.pre, r.post, r.otherwise))
            parts = [f"SELECT DISTINCT e.id AS id FROM {q(k)} e WHERE ({pre}) AND NOT ({post})"] if r.post else []
            if r.otherwise:
                parts.append(f"SELECT DISTINCT e.id AS id FROM {q(k)} e WHERE NOT ({pre}) AND NOT ({otherwise})")
            path = " => ".join(", ".join(c.slot for c in cs) for cs in (r.pre, r.post))
            if r.otherwise:
                path += " | " + ", ".join(c.slot for c in r.otherwise)
            add(k, r.name, "rule", "\nUNION\n".join(parts), path=path)
    return out


def mismatch(column: str, holder) -> str:
    """The SQL condition that a value misses one of the (portable) patterns of a slot or identifier."""
    patterns = holder.id_patterns if hasattr(holder, "id_patterns") else holder.patterns
    return " OR ".join(f"NOT RLIKE({column}, {literal(p)})" for p in patterns)


def conjunction(pack: Pack, kind: str, conditions) -> str:
    """Rule conditions on the element `e`, as SQL. A value condition holds when the slot has a value
    and every value meets it; `required` or PRESENT asks for a value, ABSENT for none."""
    out = []
    for c in conditions:
        t, f = q(pack.slot(kind, c.slot).table), c.facets
        has = f"e.id IN (SELECT id FROM {t})"
        if f.get("required") or f.get("value_presence") == "PRESENT":
            out.append(has)
        if f.get("value_presence") == "ABSENT":
            out.append(f"e.id NOT IN (SELECT id FROM {t})")
        tests = []
        if "equals_string" in f:
            tests.append(f"v = {literal(f['equals_string'])}")
        if "equals_number" in f:
            tests.append(f"v = {int(f['equals_number'])}")
        if "minimum_value" in f:
            tests.append(f"v >= {int(f['minimum_value'])}")
        if "maximum_value" in f:
            tests.append(f"v <= {int(f['maximum_value'])}")
        if "pattern" in f:
            tests.append(f"RLIKE(v, {literal(f['pattern'])})")
        if tests:
            out.append(f"{has} AND e.id NOT IN (SELECT id FROM {t} WHERE NOT ({' AND '.join(tests)}))")
    return " AND ".join(f"({x})" for x in out) or "TRUE"


def decimal(n: int | None) -> str | None:
    """Integers cross JSON boundaries as decimal strings, so JavaScript never loses precision."""
    return None if n is None else str(n)


def present(d: dict) -> dict:
    """An optional slot without a value is left out of the bundle, never written as null."""
    return {k: v for k, v in d.items() if v is not None}


def sentence(message: str, **args: str) -> dict:
    """A sentence is a message id plus arguments; every argument is an element id (see compiler.md)."""
    return {"message": message, "args": dict(sorted(args.items()))}


def placed(span) -> dict | None:
    return spans.doc(span) if span else None


def owned(said: dict, owner: str, span) -> dict:
    """A sentence of one element (MOD2): its id is `sentence:` and the owner's stable id, its span the owner's."""
    return present(said | {"id": f"sentence:{owner}", "span": placed(span)})


def stable_ids(pack: Pack) -> dict[str, str]:
    """MOD2: the stable id of each kind, `<module>/<Class>`: its module and its class name, the first one when it was
    renamed (`renamed_from`). It depends on the kind alone, so a class of the same name added in another module or
    in an import changes no id. A slot's id is `<kind's stable id>#<slot>`. Two kinds or two slots with one stable
    id, as a rename can give, are refused."""
    ids = {k: f"{kind.module}/{kind.renamed_from or kind.cls}" for k, kind in pack.kinds.items()}
    unique("kinds", ids)
    unique("slots", {s.element: slot_id(ids, s) for kind in pack.kinds.values() for s in kind.slots.values()})
    return ids


def unique(what: str, ids: dict[str, str]):
    """Refuse two elements with one stable id, naming both."""
    seen: dict[str, str] = {}
    clashes = []
    for element, sid in sorted(ids.items()):
        if sid in seen:
            clashes.append(f"{what} {seen[sid]} and {element} have the same stable id '{sid}'; "
                           "a renamed_from may not name a name another element has")
        seen.setdefault(sid, element)
    if clashes:
        raise CompileError("\n".join(clashes))


def slot_id(ids: dict[str, str], s) -> str:
    return f"{ids[s.kind]}#{s.renamed_from or s.name}"


def rule_id(head: dict, body: list) -> str:
    """MOD2: a rule's stable id, `<head relation>~<12 hex>` of its head and body as the bundle gives them. It
    depends on what the rule says, not on where it stands, so adding a rule above it changes nothing."""
    text = json.dumps({"head": head, "body": body}, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return f"{head['relation']}~{hashlib.sha256(text.encode('utf-8')).hexdigest()[:12]}"


def variable_types(prog, rule) -> list[dict]:
    """The type of each variable of a rule: from the column it binds, or integer for a result."""
    typed = {}
    for x in (*rule.body, *rule.aggregates):
        for t, c in zip(x.atom.terms, prog.relations[x.atom.relation].key):
            if ir.is_var(t):
                typed.setdefault(t, c.type)
    for a in rule.aggregates:
        typed[a.var] = "integer"
    for a in rule.assignments:
        typed[a.var] = "integer"
    return [{"name": v, "type": typed.get(v, "string")} for v in rule.variables]


# The body order of a rule that has no source order, such as a rule a view generates (MOD14).
LITERAL_ORDER = ("atom", "aggregate", "assignment", "comparison")


def rule_term(t: str, type_: str) -> dict:
    """A term of the rule IR, typed: a variable (`?x`), the wildcard of an aggregate (`_`) or a constant."""
    return {"kind": "variable" if ir.is_var(t) else "wildcard" if t == "_" else "constant", "value": t, "type": type_}


def rule_body(prog, rule, order: tuple[str, ...] | None) -> tuple[dict, list[dict]]:
    """The head and the body of a rule (MOD14), every term typed, from the final program. `order` is the kind of
    each body literal as written (`Pack.rule_bodies`); the rule IR keeps each kind in that order, so the n-th
    literal of a kind is the n-th entry of its list. Without an order: atoms, aggregates, assignments, comparisons.
    A term of an atom has the type of its column; any other the type of its variable, a constant compared with a
    variable that variable's, and any other constant its own form's (rules.py)."""
    types = {v["name"]: v["type"] for v in variable_types(prog, rule)}

    def atom(a):
        return [rule_term(t, c.type) for t, c in zip(a.terms, prog.relations[a.relation].key)]

    def typed(t, beside=None):
        source = t if ir.is_var(t) else beside if beside is not None and ir.is_var(beside) else None
        return rule_term(t, types[source] if source else ir.const_type(t))

    parts = {"atom": list(rule.body), "aggregate": list(enumerate(rule.aggregates)),
             "assignment": list(rule.assignments), "comparison": list(rule.conditions)}
    if order is None:
        order = tuple(k for k in LITERAL_ORDER for _ in parts[k])
    if sorted(order) != sorted(k for k in LITERAL_ORDER for _ in parts[k]):
        raise ValueError(f"{rule.id}: the source order of its body does not match the rule IR")
    next_of = {k: iter(v) for k, v in parts.items()}
    body = []
    for n, kind in enumerate(order, 1):
        x = next(next_of[kind])
        lit = {"kind": kind, "position": n}
        if kind == "atom":
            lit |= {"polarity": x.polarity, "relation": x.atom.relation, "terms": atom(x.atom)}
        elif kind == "aggregate":
            i, a = x
            lit |= present({"polarity": "positive", "relation": a.atom.relation, "terms": atom(a.atom),
                            "function": a.function, "over": a.over, "result": rule_term(a.var, "integer"),
                            "aggregate_position": i})
        elif kind == "assignment":
            lit |= {"polarity": "positive", "op": x.op, "terms": [typed(x.left), typed(x.right)],
                    "result": rule_term(x.var, "integer")}
        else:
            lit |= {"polarity": "positive", "op": x.op, "terms": [typed(x.left, x.right), typed(x.right, x.left)]}
            if getattr(x, "compare_as", None):
                lit["compare_as"] = x.compare_as
        body.append(lit)
    return {"relation": rule.head.relation, "terms": atom(rule.head)}, body


def bundle_checks(checks) -> list[dict]:
    """The logical checks as the bundle lists them."""
    return [present({"view": v, "relation": bundled.relation(c), "check": c, "kind": k, "subject": s or None,
                     "path": p or None})
            for v, c, k, s, _, p, _ in checks]


def rule_bundle(pack: Pack, prog) -> tuple[list, list]:
    """Rules and derived relations as the viewer needs them; message ids only, never words. A rule says what
    each of its aggregates folds, once: a witness names an aggregate by its position, and a reader
    never guesses the function from the numbers. A rule gives its head and its body in source order (MOD14), for
    every role. A column says its currency where the rules determine it. The relations the pack folds
    (`pack.folds`, fold.py) and the source order of a body (`pack.rule_bodies`) are the two things here that are
    not in the IR."""
    if not prog:
        return [], []
    folds = pack.folds
    rules, same, meaning = [], {}, {}
    for r in sorted(prog.rules.values(), key=lambda r: r.id):
        head, body = rule_body(prog, r, pack.rule_bodies.get(r.id))
        stable = rule_id(head, body)
        if stable in same:
            raise CompileError(f"rules {same[stable]} and {r.id} are the same rule; remove one")
        same[stable] = r.id
        sense = normalise.rule_sha256(r)  # D08: also in other variable names, body order or orientation
        if sense in meaning:
            raise CompileError(f"rules {meaning[sense]} and {r.id} say the same, up to the names of their variables "
                               "and the order of their literals; remove one")
        meaning[sense] = r.id
        rules.append(present({"id": r.id, "stable_id": stable, "span": placed(pack.rule_spans.get(r.id)),
                              "relation": r.head.relation, "module": r.module, "message": f"rule.{r.id}",
                              "variables": variable_types(prog, r),
                              "aggregates": [present({"position": i, "relation": a.atom.relation,
                                                      "function": a.function, "over": a.over})
                                             for i, a in enumerate(r.aggregates)] or None,
                              "head": head, "body": body,
                              "origin": {"file": r.origin[0], "line": str(r.origin[1])}}))
    held = amounts.columns(pack.rules, amounts.tables(pack))
    relations = [present({"id": n, "module": r.module, "explain": r.explain,
                          "columns": [rule_column(n, c, semantic, amount)
                                      for c, semantic, amount in zip(
                                          r.key,
                                          pack.rule_semantics.get(n, (None,) * len(r.key)),
                                          held[n],
                                          strict=True,
                                      )],
                          "world": r.world, "absence": True if r.absence else None, "outcome": r.outcome,
                          "extend": True if r.extend else None, "closes": r.closes,
                          "checks": [v for v, _ in rules_sql.checks(prog, n)] or None,
                          "fold": True if n in folds else None,
                          "kind": getattr(r, "kind", None),
                          "property": getattr(r, "property", None)})
                 for n, r in sorted(prog.relations.items()) if r.role == "derived"]
    return rules, relations


def rule_column(relation: str, column: ir.Column, semantic: dict | None, amount: str | None) -> dict:
    """One derived relation column of the schema bundle, keeping physical type and optional logical semantic."""
    if semantic is not None and semantic.get("base") != column.type:
        message = f"{relation}.{column.name}: semantic base {semantic.get('base')!r} does not match {column.type!r}"
        raise CompileError(message, [Diagnostic("R049", message)])
    return present({"name": column.name, "type": column.type, "semantic": semantic, "currency": amount})


CALC_COLUMNS = [{"name": c, "type": "string"} for c in ("subject", "value", "state", "reason")]


def calc_relations(calc_prog) -> list[dict]:
    """The calculation views a publication holds, as derived relations the viewer can explain: every
    rule's view, and the view of every version another rule names as `rule@version`. A row is (subject,
    value, state, reason), its CalcWitness the explanation; `calc` names the rule (or rule@version)."""
    if not calc_prog:
        return []
    pinned = set()

    def walk(node):
        if node.op == "rule" and node.value[1]:
            pinned.add(f"{node.value[0]}@{node.value[1]}")
        for a in node.args or ():
            walk(a)

    for v in calc_prog.versions.values():
        for d in v.definitions:
            walk(d.when)
            walk(d.value)
    views = {calc_prog.engine[r]: r for r in calc_prog.rules} | {calc_prog.versions[v].engine: v for v in pinned}
    return [{"id": view, "module": "calc", "explain": "materialize", "columns": CALC_COLUMNS, "world": "closed", "calc": name,
             "semantic": calc_semantic(calc_prog, name)}
            for view, name in sorted(views.items())]


def calc_semantic(calc_prog, name: str) -> dict:
    """The semantic type of a calculation view's value: a number or a boolean, derived by its rule, with
    the unit its versions agree on. A pinned version (`rule@version`) carries its own unit."""
    rule, _, version = name.partition("@")
    if not version:
        return calc_prog.result(rule).semantic
    base = calc_prog.types[rule]
    unit = calc_prog.versions[name].unit if base == types.NUMBER else None
    return types.Type(base, unit=unit, derived=name).semantic


def bundle(pack: Pack, checks, prog=None, calc_prog=None) -> dict:
    """The schema bundle, as contracts/bundle.yaml describes it."""
    kinds, arrows, attributes, keys, equations, pages = [], [], [], [], [], []
    ids = stable_ids(pack)
    for k, kind in pack.kinds.items():
        kinds.append(present({
            "id": k, "stable_id": ids[k], "span": placed(kind.span), "renamed_from": kind.renamed_from,
            "class": kind.cls, "layer": kind.layer, "parent": kind.parent, "abstract": kind.abstract,
            "identifier": kind.identifier, "id_type": types.of_sql(id_type(pack, k)).bundle,
            "identifier_patterns": kind.id_patterns, "module": kind.module, "table": k, "world": kind.world,
            "sentence": owned(sentence("is_a", kind=k, parent=kind.parent), ids[k], kind.span) if kind.parent else None,
            "name_attribute": pack.name(k).element if pack.name(k) else None,
            "slot_roles": {role: s.element for role, s in pack.slot_roles(k).items()} or None,
            "name_arrows": [s.element for s in pack.name_arrows(k)] or None,
            "relationship": True if kind.relationship else None,
            "ends": [s.element for s in pack.ends(k)] if kind.relationship else None,
            "plane": kind.plane, "owner": kind.owner, "fold": True if kind.fold else None,
            "iri": pack.iri.get("kinds", {}).get(k),
        }))
        pages.append({"kind": k, "path": f"/{k}/{{id}}", "fields": [s.element for s in pack.all_slots(k)]})
        for s in kind.slots.values():
            sid = slot_id(ids, s)
            common = {"id": s.element, "stable_id": sid, "span": placed(s.span), "renamed_from": s.renamed_from,
                      "kind": k, "name": s.name, "required": s.required, "table": s.table,
                      "multivalued": s.multivalued, "minimum_cardinality": decimal(s.minimum_cardinality),
                      "maximum_cardinality": decimal(s.maximum_cardinality), "world": s.world,
                      "semantic": s.type.semantic}
            mood = ("many." if s.multivalued else "") + ("total" if s.required else "partial")
            if s.arrow:
                arrows.append(present(common | {"target": s.range, "inlined": s.inlined,
                                                "sentence": owned(sentence(f"arrow.{mood}", kind=k, arrow=s.element,
                                                                           range=s.range), sid, s.span)}))
            else:
                constant = s.constant if s.constant is None or isinstance(s.constant, str) else decimal(s.constant)
                attributes.append(present(common | {"type": s.type.bundle, "schema_type": s.range,
                                            "derivation": "fact", "enum": s.enum,
                                            "minimum": decimal(s.minimum), "maximum": decimal(s.maximum),
                                            "patterns": s.patterns, "input_format": s.input_format,
                                            "constant": constant, "currency": s.currency,
                                            "sentence": owned(sentence(f"attribute.{mood}", kind=k,
                                                                       attribute=s.element), sid, s.span)}))
        for name, slots in kind.unique_keys:
            keys.append({"id": f"{k}.{name}", "kind": k, "slots": [pack.slot(k, sn).element for sn in slots],
                         "sentence": owned(sentence("unique_key", kind=k, key=f"{k}.{name}"), f"{ids[k]}.{name}",
                                           kind.spans.get(f"key:{name}"))})
        for name, left, right in kind.path_equations:
            equations.append({"id": f"{k}.{name}", "kind": k, "left": left, "right": right,
                              "sentence": owned(sentence("path_equation", kind=k, equation=f"{k}.{name}"),
                                                f"{ids[k]}.{name}", kind.spans.get(f"eq:{name}"))})
    return {
        "format": "rezono.schema-bundle/1",
        "pack": present({"id": pack.meta["name"], "version": pack.meta["version"],
                         "default_language": pack.meta["default_language"],
                         "language_version": pack.language_version,
                         "base": pack.iri.get("base")}),
        "imports": pack.imports,
        "schemas": pack.schemas,
        "layers": list(LAYERS),
        "order": sorted(pack.kinds, key=lambda k: (LAYERS.index(pack.kinds[k].layer), k)),
        "kinds": kinds,
        "arrows": arrows,
        "attributes": attributes,
        "enums": [{"id": e, "values": [f"{e}.{v}" for v in values]} for e, values in pack.enums.items()],
        "unique_keys": keys,
        "path_equations": equations,
        "rules": rule_bundle(pack, prog)[0],
        "relations": sorted(rule_bundle(pack, prog)[1] + calc_relations(calc_prog), key=lambda r: r["id"]),
        "checks": bundle_checks(checks),
        "pages": pages,
        "labels": pack.labels,
        "messages": [{"lang": lang, "resource": text} for lang, text in sorted(pack.messages.items())],
        "channels": pack.channels,
        "jurisdictions": [],
    } | ({"questions": pack.questions} if pack.questions else {}) \
      | ({"reader_questions": pack.reader_questions} if pack.reader_questions else {}) \
      | present({"reasons": pack.iri.get("reasons") or None})
