"""Translate a calc Program (calc.py) to SQL: Feldera-SQL for the engine, DuckDB-SQL for batch.

A value is a set of columns: `n`, `d` (an exact fraction of two BIGINTs, d > 0) or `b` (a boolean),
with `state` (known, unknown, not_applicable, invalid) and a `reason` when it is not known. Every
column is NOT NULL: a missing input becomes an explicit state, never NULL (formal.md section 6).

Arithmetic goes through a few pure functions with the same names in both dialects: SQL macros on
128-bit integers in DuckDB, a Rust UDF (udf/) in Feldera. A result denominator of 0 marks overflow
or division by zero: an overflow is `unknown` (W8: the value exists, Rede cannot hold it), a division
by zero `invalid`. The body of the SQL is the same text for both dialects.

Each expression node becomes columns of one rule-version view. Nodes are computed per height, in
two nested selects (first the value, then the state), so the text grows linearly with the tree.
"""

from __future__ import annotations

from .calc import BOOLEAN, BOUND, NUMBER, Node, Program, Version
from .explain import key_text
from .rules import calc_input_table
from .sqltext import literal, q

HEADER = "-- Generated by the Rede compiler from the calculation rules (calc/). Do not edit.\n"
STATES = ("invalid", "unknown", "not_applicable")
AS_OF = "calc__as_of"
PARAMETER = "calc__parameter"
PARAMETER_VALUE = "calc__parameter_value"  # parameter_values: every element grouped once, for all leaves
# The arithmetic functions: name -> argument names. Every argument and result is BIGINT NOT NULL.
FUNCTIONS = {
    "rede_add_n": "an ad bn bd", "rede_add_d": "an ad bn bd",
    "rede_sub_n": "an ad bn bd", "rede_sub_d": "an ad bn bd",
    "rede_mul_n": "an ad bn bd", "rede_mul_d": "an ad bn bd",
    "rede_div_n": "an ad bn bd", "rede_div_d": "an ad bn bd",
    "rede_cmp": "an ad bn bd",
    "rede_floor": "n d", "rede_ceil": "n d", "rede_round": "n d",
    "rede_bit": "e p",
}
CONSTANTS = ("integer", "boolean")  # a constant has no column and no witness step
POW_BITS = 6  # exponents below 2**6 are multiplied out; a larger one overflows unless the base is 0, 1 or -1


def beyond(op: str) -> str:
    """W8 (arbiter, 11-11-2026): the reason of a step beyond the bound, naming the bound and the operator."""
    return f"beyond the bound of W8 in {op}"


def big(i: int) -> str:
    return f"CAST({i} AS BIGINT)"


def varchar(expr: str) -> str:
    """Text a view gives out is VARCHAR: a CASE of literals is a CHAR(n) of its longest literal in
    Calcite, and Feldera cannot join such fixed-length columns of different lengths."""
    return f"CAST({expr} AS VARCHAR)"


def date(s: str) -> str:
    return f"DATE '{s}'"


# --- DuckDB macros: the same functions in plain SQL on HUGEINT (128 bits) -------------------------

_M = "9223372036854775807::HUGEINT"
DUCKDB_MACROS = f"""\
CREATE OR REPLACE MACRO rede__fit(x) AS (x >= -{_M} AND x <= {_M});
CREATE OR REPLACE MACRO rede__g(n, d) AS greatest(abs(gcd(n, d)), 1::HUGEINT);
CREATE OR REPLACE MACRO rede__ok(n, d) AS (d > 0 AND rede__fit(n // rede__g(n, d)) AND rede__fit(d // rede__g(n, d)));
CREATE OR REPLACE MACRO rede__n(n, d) AS CAST(CASE WHEN rede__ok(n, d) THEN n // rede__g(n, d) ELSE 0 END AS BIGINT);
CREATE OR REPLACE MACRO rede__d(n, d) AS CAST(CASE WHEN rede__ok(n, d) THEN d // rede__g(n, d) ELSE 0 END AS BIGINT);
CREATE OR REPLACE MACRO rede_add_n(an, ad, bn, bd) AS CASE WHEN ad > 0 AND bd > 0 THEN rede__n(an::HUGEINT * bd + bn::HUGEINT * ad, ad::HUGEINT * bd) ELSE 0::BIGINT END;
CREATE OR REPLACE MACRO rede_add_d(an, ad, bn, bd) AS CASE WHEN ad > 0 AND bd > 0 THEN rede__d(an::HUGEINT * bd + bn::HUGEINT * ad, ad::HUGEINT * bd) ELSE 0::BIGINT END;
CREATE OR REPLACE MACRO rede_sub_n(an, ad, bn, bd) AS CASE WHEN ad > 0 AND bd > 0 THEN rede__n(an::HUGEINT * bd - bn::HUGEINT * ad, ad::HUGEINT * bd) ELSE 0::BIGINT END;
CREATE OR REPLACE MACRO rede_sub_d(an, ad, bn, bd) AS CASE WHEN ad > 0 AND bd > 0 THEN rede__d(an::HUGEINT * bd - bn::HUGEINT * ad, ad::HUGEINT * bd) ELSE 0::BIGINT END;
CREATE OR REPLACE MACRO rede_mul_n(an, ad, bn, bd) AS CASE WHEN ad > 0 AND bd > 0 THEN rede__n(an::HUGEINT * bn, ad::HUGEINT * bd) ELSE 0::BIGINT END;
CREATE OR REPLACE MACRO rede_mul_d(an, ad, bn, bd) AS CASE WHEN ad > 0 AND bd > 0 THEN rede__d(an::HUGEINT * bn, ad::HUGEINT * bd) ELSE 0::BIGINT END;
CREATE OR REPLACE MACRO rede_div_n(an, ad, bn, bd) AS CASE WHEN ad <= 0 OR bd <= 0 OR bn = 0 THEN 0::BIGINT WHEN bn > 0 THEN rede__n(an::HUGEINT * bd, ad::HUGEINT * bn) ELSE rede__n(-(an::HUGEINT * bd), -(ad::HUGEINT * bn)) END;
CREATE OR REPLACE MACRO rede_div_d(an, ad, bn, bd) AS CASE WHEN ad <= 0 OR bd <= 0 OR bn = 0 THEN 0::BIGINT WHEN bn > 0 THEN rede__d(an::HUGEINT * bd, ad::HUGEINT * bn) ELSE rede__d(-(an::HUGEINT * bd), -(ad::HUGEINT * bn)) END;
CREATE OR REPLACE MACRO rede_cmp(an, ad, bn, bd) AS CAST(CASE WHEN an::HUGEINT * bd < bn::HUGEINT * ad THEN -1 WHEN an::HUGEINT * bd > bn::HUGEINT * ad THEN 1 ELSE 0 END AS BIGINT);
CREATE OR REPLACE MACRO rede_floor(n, d) AS CAST(CASE WHEN d <= 0 THEN 0 WHEN n >= 0 THEN n::HUGEINT // d ELSE -((-(n::HUGEINT) + d - 1) // d) END AS BIGINT);
CREATE OR REPLACE MACRO rede_ceil(n, d) AS CAST(CASE WHEN d <= 0 THEN 0 WHEN n >= 0 THEN (n::HUGEINT + d - 1) // d ELSE -(-(n::HUGEINT) // d) END AS BIGINT);
CREATE OR REPLACE MACRO rede_round(n, d) AS CAST(CASE WHEN d <= 0 THEN 0 WHEN n >= 0 THEN (2 * n::HUGEINT + d) // (2 * d::HUGEINT) ELSE -((2 * -(n::HUGEINT) + d) // (2 * d::HUGEINT)) END AS BIGINT);
CREATE OR REPLACE MACRO rede_bit(e, p) AS CAST(CASE WHEN e < 0 OR p <= 0 THEN 0 ELSE (e // p) % 2 END AS BIGINT);
"""


def feldera_functions() -> str:
    """The declarations; the bodies are in udf/udf.rs."""
    out = []
    for name, args in FUNCTIONS.items():
        params = ", ".join(f"{a} BIGINT NOT NULL" for a in args.split())
        out.append(f"CREATE FUNCTION {name}({params}) RETURNS BIGINT NOT NULL;\n")
    return "".join(out)


def call(name: str, *args: str) -> str:
    return f"{name}({', '.join(args)})"


# --- Lowering: nodes to columns ------------------------------------------------------------------

# State codes inside a view; the order is the precedence, so the state of a strict operator is the
# GREATEST of its arguments. Views show the text of contracts/value.yaml.
KNOWN, NOT_APPLICABLE, UNKNOWN, INVALID = 0, 1, 2, 3
STATE_TEXT = {KNOWN: "known", NOT_APPLICABLE: "not_applicable", UNKNOWN: "unknown", INVALID: "invalid"}


def state_text(code: str) -> str:
    return f"CASE {code} " + " ".join(f"WHEN {k} THEN '{t}'" for k, t in STATE_TEXT.items() if k != INVALID) + " ELSE 'invalid' END"


def state_code(column: str) -> str:
    """A state read from another view; a missing row is unknown."""
    return f"CASE {column} " + " ".join(f"WHEN '{t}' THEN {k}" for k, t in STATE_TEXT.items()) + f" ELSE {UNKNOWN} END"


class Cell:
    """One node as columns c<i>_n, c<i>_d (number) or c<i>_b (boolean), plus c<i>_s (state code) and
    c<i>_r (reason). A part in `lit` is a constant and has no column. A raw cell is an intermediate
    step (value only); the cell that owns it carries the state."""

    def __init__(self, i: int, typ: str, height: int, raw: bool = False):
        self.i, self.typ, self.height, self.raw = i, typ, height, raw
        self.value: dict[str, str] = {}  # n, d or b: computed in the value step
        self.state = ""  # computed in the state step
        self.reason = ""
        self.lit: dict[str, str] = {}

    def c(self, part: str) -> str:
        return self.lit.get(part, f"c{self.i}_{part}")

    @property
    def certain(self) -> bool:
        """Known whatever the facts are (a constant, or an operator on constants that cannot fail)."""
        return "s" in self.lit


class Lowering:
    def __init__(self, prog: Program, v: Version):
        self.prog, self.v = prog, v
        self.cells: list[Cell] = []
        self.joins: list[str] = []
        self.memo: dict[Node, Cell] = {}
        self.join_alias: dict[tuple, str] = {}

    def leaf(self, typ: str, value: dict[str, str], state: str, reason: str) -> Cell:
        cell = Cell(len(self.cells), typ, 0)
        cell.value, cell.state, cell.reason = value, state, reason
        self.cells.append(cell)
        return cell

    def constant(self, typ: str, value: dict[str, str]) -> Cell:
        cell = Cell(len(self.cells), typ, 0)
        cell.lit = dict(value, s=str(KNOWN), r="''")
        self.cells.append(cell)
        return cell

    def join(self, key: tuple, make) -> str:
        """One join per distinct leaf. `make(alias)` writes it: ids are user data and are never run
        through a format string, so a brace in an id stays a brace."""
        if key not in self.join_alias:
            alias = f"j{len(self.join_alias)}"
            self.join_alias[key] = alias
            self.joins.append(make(alias))
        return self.join_alias[key]

    def cell(self, typ: str, args: list[Cell], raw: bool = False) -> Cell:
        cell = Cell(len(self.cells), typ, 1 + max((a.height for a in args), default=0), raw)
        self.cells.append(cell)
        return cell

    def lower(self, node: Node) -> Cell:
        if node not in self.memo:
            self.memo[node] = self._lower(node)
        return self.memo[node]

    def _lower(self, node: Node) -> Cell:
        op = node.op
        if op == "integer":
            return self.constant(NUMBER, {"n": big(node.value), "d": big(1)})
        if op == "boolean":
            return self.constant(BOOLEAN, {"b": "TRUE" if node.value else "FALSE"})
        if op == "fact":
            return self.fact(node.value)
        if op == "parameter":
            return self.parameter(node.value)
        if op == "rule":
            return self.rule(*node.value)
        args = [self.lower(a) for a in node.args]
        if op in ("add", "sub"):
            return self.fold(op, args)
        if op in ("min", "max"):
            return self.extreme(op, args)
        if op == "ratio":
            return self.ratio(args)
        if op in ("floor", "ceil", "round"):
            x = args[0]
            cell = self.cell(NUMBER, args)
            cell.value = {"n": call(f"rede_{op}", x.c("n"), x.c("d"))}
            cell.lit["d"] = big(1)
            self.strict(cell, args, [])
            return cell
        if op == "pow":
            return self.pow(*args)
        if op == "if":
            return self.choice(*args)
        if op in ("and", "or"):
            return self.logic(op, args)
        return self.compare(op, *args)

    # --- leaves
    def fact(self, fid: str) -> Cell:
        f = self.prog.facts[fid]
        number = f.type == NUMBER
        if f.presence:
            # Whether a derived relation holds for the subject: known either way (negation as failure).
            a = self.join(("fact", fid), lambda a: f"LEFT JOIN (SELECT DISTINCT {q(f.key)} AS id FROM {q(f.table)}) {a} ON {a}.id = s.id")
            cell = self.leaf(BOOLEAN, {"b": f"({a}.id IS NOT NULL)"}, "", "")
            cell.lit.update(s=str(KNOWN), r="''")
            return cell
        col = q(f.column)
        v = col if number else f"CASE WHEN {col} THEN 1 ELSE 0 END"
        if f.table is not None:
            a = self.join(("fact", fid), lambda a: f"LEFT JOIN (SELECT {q(f.key)} AS id, MIN({v}) AS v, COUNT(DISTINCT {col}) AS c "
                                         f"FROM {q(f.table)} GROUP BY {q(f.key)}) {a} ON {a}.id = s.id")
            missing = (NOT_APPLICABLE, f"fact {fid} does not apply") if f.optional else (UNKNOWN, f"fact {fid} is missing")
        else:
            view = "calc__input_integer" if number else "calc__input_boolean"
            a = self.join(("fact", fid), lambda a: f"LEFT JOIN {q(view)} {a} ON {a}.subject = s.id AND {a}.fact = {literal(fid)}")
            missing = (UNKNOWN, f"fact {fid} is missing")
        return self.looked_up(a, number, missing, f"fact {fid}")

    def parameter(self, pid: str) -> Cell:
        if self.prog.choice:
            return self.chosen_parameter(pid)
        a = self.join(("parameter", pid), lambda a: f"LEFT JOIN {q(PARAMETER_VALUE)} {a} ON {a}.id = {literal(pid)}")
        return self.looked_up(a, True, (UNKNOWN, f"parameter {pid} is missing"), f"parameter {pid}")

    def chosen_parameter(self, name: str) -> Cell:
        """A parameter by its name, the row chosen in `calc__parameter` (choice_sql); the cell also
        records the element it read (part e), so an explanation reaches the row and its source."""
        a = self.join(("parameter", name), lambda a: f"LEFT JOIN {q(PARAMETER)} {a} ON {a}.name = {literal(name)}")
        what = f"parameter {name}"
        cases = [(f"{a}.k IS NULL", UNKNOWN, f"{what} is missing")]
        cases += [(f"{a}.k = {k}", s, r.format(what=what)) for k, (s, r) in CHOICE_STATES.items()]
        cases.append((f"{a}.v < -{BOUND}", INVALID, f"{what} does not fit 64 bits"))
        state = "CASE " + " ".join(f"WHEN {c} THEN {s}" for c, s, _ in cases) + f" ELSE {KNOWN} END"
        reason = "CASE " + " ".join(f"WHEN {c} THEN {literal(r)}" for c, _, r in cases) + " ELSE '' END"
        cell = self.leaf(NUMBER, {"n": f"COALESCE({a}.v, {big(0)})", "e": f"COALESCE({a}.e, '')"}, state, reason)
        cell.lit["d"] = big(1)
        return cell

    def looked_up(self, a: str, number: bool, missing: tuple[int, str], what: str) -> Cell:
        cases = [(f"{a}.c IS NULL", missing[0], missing[1]), (f"{a}.c > 1", INVALID, f"{what} has more than one value")]
        if number:
            cases.append((f"{a}.v < -{BOUND}", INVALID, f"{what} does not fit 64 bits"))
            value = {"n": f"COALESCE({a}.v, {big(0)})"}
        else:
            value = {"b": f"(COALESCE({a}.v, 0) = 1)"}
        state = "CASE " + " ".join(f"WHEN {c} THEN {s}" for c, s, _ in cases) + f" ELSE {KNOWN} END"
        reason = "CASE " + " ".join(f"WHEN {c} THEN {literal(r)}" for c, _, r in cases) + " ELSE '' END"
        cell = self.leaf(NUMBER if number else BOOLEAN, value, state, reason)
        if number:
            cell.lit["d"] = big(1)
        return cell

    def rule(self, name: str, version: str | None) -> Cell:
        view = self.prog.versions[f"{name}@{version}"].engine if version else self.prog.engine[name]
        a = self.join(("rule", name, version), lambda a: f"LEFT JOIN {q(view)} {a} ON {a}.subject = s.id")
        typ = self.prog.types[name]
        value = ({"n": f"COALESCE({a}.n, {big(0)})", "d": f"COALESCE({a}.d, {big(1)})"} if typ == NUMBER
                 else {"b": f"COALESCE({a}.b, FALSE)"})
        missing = literal(f"rule {name} has no value")
        return self.leaf(typ, value, state_code(f"{a}.state"), f"COALESCE({a}.reason, {missing})")

    # --- operators
    def strict(self, cell: Cell, args: list[Cell], own: list[tuple[str, int, str]]) -> None:
        """The most severe state of the arguments (invalid, unknown, not_applicable), with the reason of
        the first argument that has it; then the operator's own conditions (condition, state, reason), in order."""
        dyn = [a for a in args if not a.certain]
        if not dyn and not own:
            cell.lit.update(s=str(KNOWN), r="''")
            return
        ws, wr = [], []
        if dyn:
            worst = dyn[0].c("s") if len(dyn) == 1 else f"GREATEST({', '.join(a.c('s') for a in dyn)})"
            first = (dyn[0].c("r") if len(dyn) == 1 else
                     "CASE " + " ".join(f"WHEN {a.c('s')} = {worst} THEN {a.c('r')}" for a in dyn) + " ELSE '' END")
            ws.append(f"WHEN {worst} > {KNOWN} THEN {worst}")
            wr.append(f"WHEN {worst} > {KNOWN} THEN {first}")
        for cond, state, reason in own:
            ws.append(f"WHEN {cond} THEN {state}")
            wr.append(f"WHEN {cond} THEN {literal(reason)}")
        cell.state = "CASE " + " ".join(ws) + f" ELSE {KNOWN} END"
        cell.reason = "CASE " + " ".join(wr) + " ELSE '' END"

    def binary(self, fn: str, a: Cell, b: Cell, raw: bool = True) -> Cell:
        cell = self.cell(NUMBER, [a, b], raw)
        args = (a.c("n"), a.c("d"), b.c("n"), b.c("d"))
        cell.value = {"n": call(f"{fn}_n", *args), "d": call(f"{fn}_d", *args)}
        return cell

    def fold(self, op: str, args: list[Cell]) -> Cell:
        acc = args[0]
        for b in args[1:]:
            acc = self.binary(f"rede_{op}", acc, b)
        acc.raw = False
        self.strict(acc, args, [(f"{acc.c('d')} = 0", UNKNOWN, beyond(op))])
        return acc

    def extreme(self, op: str, args: list[Cell]) -> Cell:
        acc = args[0]
        keep = "<=" if op == "min" else ">="
        for b in args[1:]:
            cell = self.cell(NUMBER, [acc, b], raw=True)
            first = f"{call('rede_cmp', acc.c('n'), acc.c('d'), b.c('n'), b.c('d'))} {keep} 0"
            cell.value = {p: f"CASE WHEN {first} THEN {acc.c(p)} ELSE {b.c(p)} END" for p in ("n", "d")}
            acc = cell
        acc.raw = False
        self.strict(acc, args, [])
        return acc

    def ratio(self, args: list[Cell]) -> Cell:
        x, n, d = args
        out = self.binary("rede_div", self.binary("rede_mul", x, n), d)
        out.raw = False
        self.strict(out, args, [(f"{d.c('n')} = 0", INVALID, "division by zero in ratio"),
                                (f"{out.c('d')} = 0", UNKNOWN, beyond("ratio"))])
        return out

    def pow(self, b: Cell, e: Cell) -> Cell:
        one = {"n": big(1), "d": big(1)}
        powers = [b]
        for _ in range(1, POW_BITS):
            powers.append(self.binary("rede_mul", powers[-1], powers[-1]))
        acc = None
        for k, p in enumerate(powers):
            bit = f"{call('rede_bit', e.c('n'), big(2 ** k))} = 1"
            cell = self.cell(NUMBER, [e, p] + ([acc] if acc else []), raw=True)
            if acc is None:
                cell.value = {x: f"CASE WHEN {bit} THEN {p.c(x)} ELSE {one[x]} END" for x in ("n", "d")}
            else:
                args = (acc.c("n"), acc.c("d"), p.c("n"), p.c("d"))
                cell.value = {x: f"CASE WHEN {bit} THEN {call(f'rede_mul_{x}', *args)} ELSE {acc.c(x)} END" for x in ("n", "d")}
            acc = cell
        out = self.cell(NUMBER, [b, e, acc])
        unit = f"{b.c('d')} = 1 AND ({b.c('n')} = 1 OR {b.c('n')} = -1)"
        odd = f"{call('rede_bit', e.c('n'), big(1))} = 1"
        large_n = (f"CASE WHEN {b.c('n')} = 0 THEN {big(0)} WHEN {unit} THEN "
                   f"(CASE WHEN {b.c('n')} = -1 AND {odd} THEN {big(-1)} ELSE {big(1)} END) ELSE {big(0)} END")
        large_d = f"CASE WHEN {b.c('n')} = 0 OR ({unit}) THEN {big(1)} ELSE {big(0)} END"
        limit = f"{e.c('n')} >= {2 ** POW_BITS}"
        out.value = {"n": f"CASE WHEN {limit} THEN {large_n} ELSE {acc.c('n')} END",
                     "d": f"CASE WHEN {limit} THEN {large_d} ELSE {acc.c('d')} END"}
        self.strict(out, [b, e], [(f"{e.c('d')} <> 1 OR {e.c('n')} < 0", INVALID, "exponent of pow is not a natural number"),
                                  (f"{out.c('d')} = 0", UNKNOWN, beyond("pow"))])
        return out

    def choice(self, c: Cell, a: Cell, b: Cell) -> Cell:
        """Only the chosen branch counts: its state, value and reason."""
        cell = self.cell(a.typ, [c, a, b])
        cond = c.c("b")
        parts = ("n", "d") if a.typ == NUMBER else ("b",)
        cell.value = {p: f"CASE WHEN {cond} THEN {a.c(p)} ELSE {b.c(p)} END" for p in parts}
        if c.certain and a.certain and b.certain:
            cell.lit.update(s=str(KNOWN), r="''")
            return cell
        head_s = f"WHEN {c.c('s')} > {KNOWN} THEN {c.c('s')} " if not c.certain else ""
        head_r = f"WHEN {c.c('s')} > {KNOWN} THEN {c.c('r')} " if not c.certain else ""
        cell.state = f"CASE {head_s}WHEN {cond} THEN {a.c('s')} ELSE {b.c('s')} END"
        cell.reason = f"CASE {head_r}WHEN {cond} THEN {a.c('r')} ELSE {b.c('r')} END"
        return cell

    def logic(self, op: str, args: list[Cell]) -> Cell:
        """and: false as soon as one argument is a known false; or: true as soon as one is a known
        true. Invalid still blocks first; then unknown, then not_applicable."""
        decisive = "NOT " if op == "and" else ""
        cell = self.cell(BOOLEAN, args)
        hits = [f"({a.c('s')} = {KNOWN} AND {decisive}{a.c('b')})" for a in args]
        any_hit = "(" + " OR ".join(hits) + ")"
        cell.value = {"b": f"(NOT {any_hit})" if op == "and" else any_hit}
        dyn = [a for a in args if not a.certain]
        if not dyn:
            cell.lit.update(s=str(KNOWN), r="''")
            return cell
        worst = dyn[0].c("s") if len(dyn) == 1 else f"GREATEST({', '.join(a.c('s') for a in dyn)})"
        first = (dyn[0].c("r") if len(dyn) == 1 else
                 "CASE " + " ".join(f"WHEN {a.c('s')} = {worst} THEN {a.c('r')}" for a in dyn) + " ELSE '' END")
        cell.state = f"CASE WHEN {worst} = {INVALID} THEN {INVALID} WHEN {any_hit} THEN {KNOWN} ELSE {worst} END"
        cell.reason = f"CASE WHEN {worst} = {INVALID} THEN {first} WHEN {any_hit} THEN '' WHEN {worst} > {KNOWN} THEN {first} ELSE '' END"
        return cell

    def compare(self, op: str, a: Cell, b: Cell) -> Cell:
        cell = self.cell(BOOLEAN, [a, b])
        if a.typ == BOOLEAN:
            cell.value = {"b": f"({a.c('b')} = {b.c('b')})"}
        else:
            sign = {"eq": "=", "lt": "<", "lte": "<=", "gte": ">="}[op]
            cell.value = {"b": f"({call('rede_cmp', a.c('n'), a.c('d'), b.c('n'), b.c('d'))} {sign} 0)"}
        self.strict(cell, [a, b], [])
        return cell

    def negate(self, a: Cell) -> Cell:
        cell = self.cell(BOOLEAN, [a])
        cell.value = {"b": f"(NOT {a.c('b')})"}
        if a.certain:
            cell.lit.update(s=str(KNOWN), r="''")
        else:
            cell.state, cell.reason = a.c("s"), a.c("r")
        return cell

    # --- the view of one rule version
    def applies(self) -> list[Cell]:
        """Default logic: a definition applies when its condition holds and no definition that goes
        before it applies."""
        defs = {d.id: d for d in self.v.definitions}
        overriders = {d.id: [o.id for o in self.v.definitions if d.id in o.before] for d in self.v.definitions}
        memo: dict[str, Cell] = {}

        def app(did: str) -> Cell:
            if did not in memo:
                when = self.lower(defs[did].when)
                if overriders[did]:
                    memo[did] = self.logic("and", [when] + [self.negate(app(o)) for o in overriders[did]])
                else:
                    memo[did] = when
            return memo[did]

        return [app(d.id) for d in self.v.definitions]

    def recorded(self) -> list[Cell]:
        """The cells of the program's nodes that are no constant, once each: the columns of the witness
        (docs/compiler.md, "Design M3: calculation witnesses"). Equal nodes share a cell (memo)."""
        cells = {}
        for d in self.v.definitions:
            for root in (d.when, d.value):
                for node in nodes(root):
                    if node.op not in CONSTANTS:
                        cells.setdefault(self.memo[node].i, self.memo[node])
        return [cells[i] for i in sorted(cells)]

    def sql(self, witness: str) -> tuple[str, str]:
        """(the witness relation, the version view that reads it): the version is a projection of its
        witness, so nothing is computed twice."""
        apps = self.applies()
        values = [self.lower(d.value) for d in self.v.definitions]
        typ = self.prog.types[self.v.rule]
        base = ["s.id AS subject"]
        for c in self.cells:
            if c.height == 0:
                base += [f"{e} AS {c.c(p)}" for p, e in c.value.items() if p not in c.lit]
                if not c.certain:
                    base += [f"{c.state} AS {c.c('s')}", f"{c.reason} AS {c.c('r')}"]
        subjects = f"(SELECT DISTINCT id FROM {q(self.prog.subject_table)}) s"
        body = f"SELECT {', '.join(base)}\nFROM {subjects}" + "".join(f"\n{j}" for j in self.joins)
        top = max(c.height for c in self.cells)
        for h in range(1, top + 1):
            level = [c for c in self.cells if c.height == h]
            vals = [f"{e} AS {c.c(p)}" for c in level for p, e in c.value.items() if p not in c.lit]
            if vals:
                body = f"SELECT t.*, {', '.join(vals)}\nFROM ({body}) t"
            states = [f"{c.state} AS {c.c('s')}, {c.reason} AS {c.c('r')}" for c in level if not c.raw and not c.certain]
            if states:
                body = f"SELECT t.*, {', '.join(states)}\nFROM ({body}) t"
        vid = self.v.id
        hit = [f"({a.c('s')} = {KNOWN} AND {a.c('b')})" for a in apps]
        count = " + ".join(f"CASE WHEN {h} THEN 1 ELSE 0 END" for h in hit)
        # (condition, state, reason, chosen definition), first match wins: an invalid condition, two
        # definitions that both apply, an unknown condition, the one that applies, not applicable.
        unsure = [a for a in apps if not a.certain]
        arms = [(f"{a.c('s')} = {INVALID}", str(INVALID), a.c("r"), "0") for a in unsure]
        if len(apps) > 1:
            arms.append((f"{count} > 1", str(INVALID), literal(f"more than one definition of {vid} applies"), "0"))
        arms += [(f"{a.c('s')} = {UNKNOWN}", str(UNKNOWN), a.c("r"), "0") for a in unsure]
        arms += [(h, v.c("s"), v.c("r"), str(k + 1)) for k, (h, v) in enumerate(zip(hit, values))]
        arms += [(f"{a.c('s')} = {NOT_APPLICABLE}", str(NOT_APPLICABLE), a.c("r"), "0") for a in unsure]
        default = (str(NOT_APPLICABLE), literal(f"no definition of {vid} applies"), "0")

        def case(k: int) -> str:
            return "CASE " + " ".join(f"WHEN {arm[0]} THEN {arm[k]}" for arm in arms) + f" ELSE {default[k - 1]} END"

        body = f"SELECT t.*, {case(3)} AS pick, {case(1)} AS state, {case(2)} AS reason\nFROM ({body}) t"
        cols = ["t.subject", "t.pick", "t.state", "t.reason"]
        for c in self.recorded():
            cols += [f"{c.c(p)} AS {column(c.i, p)}" for p in parts(c.typ)]
            if "e" in c.value:
                cols.append(f"{varchar(c.c('e'))} AS {column(c.i, 'e')}")
            cols += [f"{c.c('s')} AS {column(c.i, 's')}", f"{varchar(c.c('r'))} AS {column(c.i, 'r')}"]
        witness_sql = f"SELECT {', '.join(cols)}\nFROM ({body}) t"

        def chosen(part: str, default: str) -> str:
            arms_ = " ".join(f"WHEN {k + 1} THEN {v.c(part)}" for k, v in enumerate(values))
            return f"CASE WHEN t.state = {KNOWN} THEN (CASE t.pick {arms_} ELSE {default} END) ELSE {default} END"

        if typ == NUMBER:
            n, d, b = chosen("n", big(0)), chosen("d", big(1)), "FALSE"
        else:
            n, d, b = big(0), big(1), chosen("b", "FALSE")
        names = " ".join(f"WHEN {k + 1} THEN {literal(x.name)}" for k, x in enumerate(self.v.definitions))
        return witness_sql, (f"SELECT t.subject, {n} AS n, {d} AS d, {b} AS b, {varchar(state_text('t.state'))} AS state, "
                             f"{varchar('t.reason')} AS reason, {varchar(f'CASE t.pick {names} ELSE {chr(39)}{chr(39)} END')} AS definition\n"
                             f"FROM {q(witness)} t")


def column(i: int, part: str) -> str:
    """The column of a cell's part (n, d, b, s or r) in the version's witness."""
    return f"c{i}_{part}"


def parts(typ: str) -> tuple[str, ...]:
    return ("n", "d") if typ == NUMBER else ("b",)


def nodes(node: Node):
    """Every node of an expression, a node before its arguments."""
    yield node
    for a in node.args:
        yield from nodes(a)


def witness_name(v: Version) -> str:
    return f"{v.engine}__witness"


def selection_sql(prog: Program, rule: str) -> str:
    """The value of a rule: the version that is valid on the evaluation date and known by then,
    the latest knowledge first (Program.version_order)."""
    order = prog.version_order(rule)
    vs = [prog.versions[v] for v in order]
    valid = " OR ".join(f"(a.valid_at >= {date(v.valid_from)} AND a.valid_at < {date(v.valid_until)})" for v in vs)
    arms = " ".join(f"WHEN a.valid_at >= {date(v.valid_from)} AND a.valid_at < {date(v.valid_until)} "
                    f"AND a.known_at >= {date(v.known_from)} THEN {i + 1}" for i, v in enumerate(vs))
    as_of = (f"(SELECT id, MIN(valid_at) AS valid_at, MIN(known_at) AS known_at, "
             f"COUNT(DISTINCT valid_at) + COUNT(DISTINCT known_at) AS c FROM {q(AS_OF)} GROUP BY id)")
    sel = (f"CASE WHEN a.c IS NULL THEN -1 WHEN a.c > 2 THEN -2 WHEN NOT ({valid}) THEN -3 {arms} ELSE -4 END")
    inner = (f"SELECT s.id AS subject, {sel} AS sel\nFROM (SELECT DISTINCT id FROM {q(prog.subject_table)}) s\n"
             f"LEFT JOIN {as_of} a ON a.id = 'as_of'")
    fixed = {-1: ("unknown", "no evaluation date (as_of)"), -2: ("invalid", "more than one evaluation date (as_of)"),
             -3: ("not_applicable", f"no version of {rule} is valid on the evaluation date"),
             -4: ("unknown", f"no version of {rule} is known on the evaluation date")}

    def pick(col: str, default: str, own: dict[int, str] | None = None) -> str:
        arms = [f"WHEN {k} THEN {e}" for k, e in (own or {}).items()]
        arms += [f"WHEN {i + 1} THEN COALESCE(v{i}.{col}, {default})" for i in range(len(vs))]
        return f"CASE t.sel {' '.join(arms)} ELSE {default} END"

    cols = [
        "t.subject",
        f"{pick('n', big(0))} AS n", f"{pick('d', big(1))} AS d", f"{pick('b', 'FALSE')} AS b",
        f"{varchar(pick('state', repr('unknown'), {k: repr(s) for k, (s, _) in fixed.items()}))} AS state",
        f"{varchar(pick('reason', literal('no value'), {k: literal(r) for k, (_, r) in fixed.items()}))} AS reason",
        f"{varchar(pick('definition', repr('')))} AS definition",
        varchar("CASE t.sel " + " ".join(f"WHEN {i + 1} THEN {literal(v.version)}" for i, v in enumerate(vs)) + " ELSE '' END") + " AS version",
    ]
    joins = "".join(f"\nLEFT JOIN {q(v.engine)} v{i} ON v{i}.subject = t.subject" for i, v in enumerate(vs))
    return f"SELECT {', '.join(cols)}\nFROM ({inner}) t{joins}"


# The outcome of choosing a parameter's row, as a code in calc__parameter.k (0 is chosen).
CHOICE_STATES = {
    1: (UNKNOWN, "no evaluation date (as_of)"),
    2: (INVALID, "more than one evaluation date (as_of)"),
    3: (UNKNOWN, "{what} has no row valid on the evaluation date"),
    4: (UNKNOWN, "{what} is not known on the evaluation date"),
    5: (INVALID, "{what} has more than one value"),
}


def choice_sql(prog: Program) -> str:
    """calc__parameter(name, k, v, e): per parameter name the row a leaf reads (W10 for parameters).
    Of the rows valid on `valid_at` and known by `known_at`, the latest knowledge date, then the latest
    validity; two values left there are invalid, and of equal rows the smallest element id is named.
    k says why there is none: no or two evaluation dates, no valid row, none known yet."""
    c, val = prog.choice, prog.parameters.table
    known = c.get("known_from")
    knowledge_column = ", k.v AS kf" if known else ""
    knowledge_join = f" JOIN {q(known.table)} k ON k.id = n.id" if known else ""
    rows = (f"(SELECT n.id AS e, n.v AS name, x.v AS v, f.v AS vf, u.v AS vu{knowledge_column} FROM {q(c['name'].table)} n "
            f"JOIN {q(val)} x ON x.id = n.id JOIN {q(c['valid_from'].table)} f ON f.id = n.id "
            f"JOIN {q(c['valid_until'].table)} u ON u.id = n.id{knowledge_join})")
    as_of = (f"(SELECT MIN(valid_at) AS valid_at, MIN(known_at) AS known_at, "
             f"COUNT(DISTINCT valid_at) + COUNT(DISTINCT known_at) AS c FROM {q(AS_OF)} WHERE id = 'as_of')")
    valid = "a.c = 2 AND p.vf <= a.valid_at AND a.valid_at < p.vu"
    knowledge_filter = " AND p.kf <= a.known_at" if known else ""
    usable = f"(SELECT p.* FROM {rows} p, {as_of} a WHERE {valid}{knowledge_filter})"
    latest = (f"(SELECT q1.* FROM {usable} q1 JOIN (SELECT name, MAX(kf) AS kf FROM {usable} q0 GROUP BY name) t "
              f"ON t.name = q1.name AND t.kf = q1.kf)") if known else usable
    chosen = (f"(SELECT q2.name, MIN(q2.v) AS v, COUNT(DISTINCT q2.v) AS c, MIN(q2.e) AS e FROM {latest} q2 "
              f"JOIN (SELECT name, MAX(vf) AS vf FROM {latest} q3 GROUP BY name) t ON t.name = q2.name AND t.vf = q2.vf "
              f"GROUP BY q2.name)")
    names = f"(SELECT p.name, SUM(CASE WHEN {valid} THEN 1 ELSE 0 END) AS nv FROM {rows} p, {as_of} a GROUP BY p.name)"
    k = "CASE WHEN a.c = 0 THEN 1 WHEN a.c > 2 THEN 2 WHEN g.nv = 0 THEN 3 WHEN ch.c IS NULL THEN 4 WHEN ch.c > 1 THEN 5 ELSE 0 END"
    e = varchar(f"CASE WHEN {k} = 0 THEN ch.e ELSE '' END")
    return (f"SELECT g.name, {k} AS k, COALESCE(ch.v, {big(0)}) AS v, {e} AS e\n"
            f"FROM {names} g CROSS JOIN {as_of} a LEFT JOIN {chosen} ch ON ch.name = g.name")


def input_views(prog: Program) -> list[tuple[str, str]]:
    if prog.inputs is None:
        return []
    out = []
    s, f = prog.inputs["subject"], prog.inputs["fact"]
    for typ, view in (("integer", "calc__input_integer"), ("boolean", "calc__input_boolean")):
        slot = prog.inputs[typ]
        if slot is None:
            continue
        v = "i.v" if typ == "integer" else "CASE WHEN i.v THEN 1 ELSE 0 END"
        out.append((view, f"SELECT s.v AS subject, f.v AS fact, MIN({v}) AS v, COUNT(DISTINCT i.v) AS c\n"
                          f"FROM {q(s.table)} s JOIN {q(f.table)} f ON f.id = s.id JOIN {q(slot.table)} i ON i.id = s.id\n"
                          f"GROUP BY s.v, f.v"))
    return out


def parameter_values(prog: Program) -> list[tuple[str, str]]:
    """calc__parameter_value(id, v, c): every parameter element with its least value and its number of values,
    grouped once; a leaf joins it on its element. A grouping per leaf put 412 group-bys in one statement of a
    pack with a table of 68 bands, and DuckDB keeps a hash table per group-by and thread: 4 GiB and 75 s, where
    grouping once takes 0.3 GiB and 1 s (an example pack, 16-11-2026)."""
    if prog.parameters is None or prog.choice:
        return []
    return [(PARAMETER_VALUE, f"SELECT id, MIN(v) AS v, COUNT(DISTINCT v) AS c FROM {q(prog.parameters.table)} GROUP BY id")]


def relations(prog: Program) -> list[tuple[str, str, bool]]:
    """(engine name, select, is a rule's output) in dependency order."""
    out = [(name, body, False) for name, body in input_views(prog) + parameter_values(prog)]
    if prog.choice:
        out.append((PARAMETER, choice_sql(prog), False))
    for kind, key in prog.order:
        if kind == "version":
            v = prog.versions[key]
            witness, version = Lowering(prog, v).sql(witness_name(v))
            out += [(witness_name(v), witness, False), (v.engine, version, False)]
        else:
            out.append((prog.engine[key], selection_sql(prog, key), True))
    return out


def rule_input_view(selection: str) -> tuple[str, str]:
    """Project exactly the known whole-number rows of a calculation for rule evaluation."""
    return calc_input_table(selection), (
        f"SELECT subject, n AS value, state, reason FROM {q(selection)} "
        "WHERE state = 'known' AND d = 1 AND reason = ''"
    )


def duckdb_rule_inputs(selections):
    """Materialize the same rule inputs as the Feldera projection, after calculation."""
    return [f"CREATE OR REPLACE TABLE {q(name)} AS\n{body};"
            for name, body in (rule_input_view(selection) for selection in selections)]


def derived_reads(prog: Program) -> list[str]:
    """The derived relations of the rules that the calculation reads, sorted."""
    return sorted({f.table for f in prog.facts.values() if f.derived})


def table_reads(prog: Program) -> list[str]:
    """The tables the calculation reads, sorted: the subject's, the parameters', the input kind's, the
    attributes its facts read, and the evaluation date. With the rules split, the loader sends these to
    its pipeline (engine/pipelines.json)."""
    out = {prog.subject_table, AS_OF}
    if prog.parameters is not None:
        out.add(prog.parameters.table)
    out |= {s.table for s in (prog.choice or {}).values()}
    out |= {prog.inputs[role].table for role in ("subject", "fact", "integer", "boolean")
            if prog.inputs and prog.inputs[role] is not None}
    out |= {f.table for f in prog.facts.values() if f.table is not None and not f.derived}
    return sorted(out)


AS_OF_TABLE = f"CREATE TABLE {q(AS_OF)} (id VARCHAR NOT NULL, valid_at DATE NOT NULL, known_at DATE NOT NULL);\n"


def feldera(prog: Program) -> str:
    """engine/calc.sql: the UDF declarations, the evaluation-date table and one view per rule version
    and per rule (materialized, so it can be read)."""
    out = [HEADER, feldera_functions(), AS_OF_TABLE]
    for name, body, output in relations(prog):
        kind = "CREATE MATERIALIZED VIEW" if output else "CREATE VIEW"
        out.append(f"{kind} {q(name)} AS\n{body};\n")
    return "".join(out)


def duckdb_prelude() -> str:
    return DUCKDB_MACROS + AS_OF_TABLE.replace("CREATE TABLE", "CREATE TABLE IF NOT EXISTS")


def duckdb_body(prog: Program) -> str:
    """Materialize in dependency order: a view per rule would recompute shared rules again and again."""
    return "".join(f"CREATE OR REPLACE TABLE {q(name)} AS\n{body};\n" for name, body, _ in relations(prog))


def duckdb(prog: Program) -> str:
    """batch/calc.sql: macros, the evaluation-date table, then one table per relation."""
    return HEADER + duckdb_prelude() + duckdb_body(prog)


def rows(prog: Program) -> dict[str, list[dict]]:
    """engine/calc.json: the evaluation date as a fact row, so a What-if can change it."""
    if prog.as_of is None:
        return {AS_OF: []}
    return {AS_OF: [{"id": "as_of", "valid_at": prog.as_of[0], "known_at": prog.as_of[1]}]}


def outputs(prog: Program) -> list[dict]:
    """Per rule: its engine view, output, type and versions, for the bundle and the readers."""
    return [{"rule": r, "view": prog.engine[r], "output": prog.versions[vs[0]].output, "type": prog.types[r],
             "versions": [{"id": v, "view": prog.versions[v].engine} for v in vs]}
            for r, vs in prog.rules.items()]


# --- Witnesses: the witness relations read back as CalcWitness (contracts/proof.yaml) -------------

def witnesses(con, prog: Program) -> list[dict]:
    """Every calculation witness of a computed program (decision W12): one per row of each rule's view,
    and one per row of a version that a rule names as `rule@version`. It reads the witness relations
    on a DuckDB connection and evaluates nothing: an `if` is followed by its recorded condition."""
    dates = con.execute(f"SELECT DISTINCT valid_at, known_at FROM {q(AS_OF)} WHERE id = 'as_of'").fetchall()
    valid_at, known_at = (str(dates[0][0]), str(dates[0][1])) if len(dates) == 1 else ("", "")
    derived = {}
    for f in sorted(prog.facts.values(), key=lambda f: f.id):
        if f.derived and f.table not in derived:
            for row in con.execute(f"SELECT {q(f.key)}, * FROM {q(f.table)}").fetchall():
                derived.setdefault(f.table, {}).setdefault(str(row[0]), set()).add(key_text(row[1:]))
    # The row of every rule and version view by subject, (subject, value, state, reason): what a witness
    # concludes, and what a rule leaf reads.
    keys: dict[str, dict[str, str]] = {}
    for view, typ in [(prog.engine[r], prog.types[r]) for r in prog.rules] + [(v.engine, prog.types[v.rule]) for v in prog.versions.values()]:
        keys[view] = {str(r[0]): key_text([str(r[0]), value_text(typ, r[4], *r[1:4]), r[4], r[5]])
                      for r in con.execute(f"SELECT subject, n, d, b, state, reason FROM {q(view)}").fetchall()}
    lowered, rows = {}, {}
    for vid, v in prog.versions.items():
        lowered[vid] = Lowering(prog, v)
        lowered[vid].sql(witness_name(v))
        cur = con.execute(f"SELECT * FROM {q(witness_name(v))}")
        names = [c[0] for c in cur.description]
        rows[vid] = {str(r[0]): dict(zip(names, r)) for r in cur.fetchall()}

    def one(rule: str, view: str, vid: str | None, row: tuple, dates: tuple[str, str]) -> dict:
        subject, n, d, b, state, reason, definition = (str(row[0]),) + tuple(row[1:7])
        steps, premises = [], set()
        if vid is not None:
            steps, premises = trace(prog, prog.versions[vid], lowered[vid], rows[vid][subject], subject, derived, keys)
        return {"conclusion": {"relation": view, "key": keys[view][subject]}, "rule": rule,
                "version": prog.versions[vid].version if vid else "", "valid_at": dates[0], "known_at": dates[1],
                "definition": definition, "value": value_text(prog.types[rule], state, n, d, b), "state": state,
                "reason": reason, "premises": [{"relation": r, "key": k} for r, k in sorted(premises)],
                "reads": reads(prog, vid), "steps": steps}

    out = []
    for rule in prog.rules:
        view = prog.engine[rule]
        for row in con.execute(f"SELECT subject, n, d, b, state, reason, definition, version FROM {q(view)}").fetchall():
            vid = f"{rule}@{row[7]}" if row[7] else None
            out.append(one(rule, view, vid, row, (valid_at, known_at) if vid else ("", "")))
    pinned = sorted({f"{n.value[0]}@{n.value[1]}" for v in prog.versions.values() for d in v.definitions
                     for root in (d.when, d.value) for n in nodes(root) if n.op == "rule" and n.value[1]})
    for vid in pinned:
        v = prog.versions[vid]
        for row in con.execute(f"SELECT subject, n, d, b, state, reason, definition FROM {q(v.engine)}").fetchall():
            out.append(one(v.rule, v.engine, vid, row, ("", "")))
    return sorted(out, key=lambda w: (w["conclusion"]["relation"], w["conclusion"]["key"]))


def reads(prog: Program, vid: str | None) -> list[str]:
    """Every relation an evaluation of a version reads, sorted (the evaluation date always): an absence
    decides a state there, so a role must read each in full to see the result (decision O8)."""
    out = {AS_OF}
    if vid is not None:
        for d in prog.versions[vid].definitions:
            for root in (d.when, d.value):
                for n in nodes(root):
                    if n.op == "parameter":
                        out.add(prog.parameters.table)
                        out |= {s.table for s in (prog.choice or {}).values()}
                    elif n.op == "fact" and prog.facts[n.value].table is not None:
                        out.add(prog.facts[n.value].table)
                    elif n.op == "fact":
                        typ = "integer" if prog.facts[n.value].type == NUMBER else "boolean"
                        out.update(prog.inputs[role].table for role in ("subject", "fact", typ))
    return sorted(out)


def trace(prog: Program, v: Version, lowering: Lowering, row: dict, subject: str, derived: dict,
          keys: dict) -> tuple[list, set]:
    """The steps of one version for one subject, in evaluation order, and the premises its leaves read."""
    steps, premises = [], set()

    def visit(node: Node, path: str) -> None:
        if node.op in CONSTANTS:
            return
        c = lowering.memo[node]
        state = STATE_TEXT[row[column(c.i, "s")]]
        values = [row[column(c.i, p)] for p in parts(c.typ)]
        n, d, b = (values[0], values[1], False) if c.typ == NUMBER else (0, 1, values[0])
        steps.append({"path": path, "op": node.op} | uses(prog, node)
                     | {"value": value_text(c.typ, state, n, d, b), "state": state,
                        "reason": "" if state == "known" else row[column(c.i, "r")]})
        if node.op == "parameter":
            # The row it read: chosen by the engine, or the element the leaf names when it exists.
            element = row[column(c.i, "e")] if prog.choice else ("" if state == "unknown" else node.value)
            if element:
                steps[-1]["element"] = element
        if node.op == "rule":
            name, version = node.value
            view = prog.versions[f"{name}@{version}"].engine if version else prog.engine[name]
            premises.add((view, keys[view][subject]))
        elif node.op == "fact" and prog.facts[node.value].derived:
            f = prog.facts[node.value]
            premises.update((f.table, k) for k in derived.get(f.table, {}).get(subject, ()))
        if node.op != "if":
            for k, a in enumerate(node.args):
                visit(a, f"{path}/{k}")
            return
        cond = node.args[0]
        visit(cond, f"{path}/0")
        if cond.op == "boolean":
            taken = 1 if cond.value else 2
        else:
            cc = lowering.memo[cond]
            known = row[column(cc.i, "s")] == KNOWN
            taken = (1 if row[column(cc.i, "b")] else 2) if known else None
        if taken is not None:
            visit(node.args[taken], f"{path}/{taken}")

    for d in v.definitions:
        visit(d.when, f"{d.name}/when")
    for k, d in enumerate(v.definitions):
        if row["pick"] == k + 1:
            visit(d.value, f"{d.name}/value")
    return steps, premises


def uses(prog: Program, node: Node) -> dict:
    """What a leaf reads, so an explanation names and links it: `ref` the fact, the parameter or the
    rule (`rule@version`) as the program names it, `relation` the table or view it is read from (none
    for an input concept, which reads the input kind's tables). An operator reads only its arguments."""
    if node.op == "fact":
        table = prog.facts[node.value].table
        return {"ref": node.value} | ({"relation": table} if table else {})
    if node.op == "parameter":
        return {"ref": node.value, "relation": prog.parameters.table}
    if node.op == "rule":
        name, version = node.value
        view = prog.versions[f"{name}@{version}"].engine if version else prog.engine[name]
        return {"ref": f"{name}@{version}" if version else name, "relation": view}
    return {}


def value_text(typ: str, state: str, n: int, d: int, b: bool) -> str:
    """Canonical text of a value: "7", "-7/2", "true"; empty unless known. As written, not through a
    fraction: a value that is not in lowest terms shows up as a difference."""
    if state != "known":
        return ""
    if typ != NUMBER:
        return "true" if b else "false"
    return str(n) if d == 1 else f"{n}/{d}"
